/**
 * Kernova Planning & Reflection Types
 *
 * Type definitions for:
 * - Agent Planning (Plan-and-Execute pattern)
 * - Self-Reflection (output evaluation)
 * - Conversation History Manager (sliding window + summarization)
 * - RAG Pipeline (document chunking + retrieval)
 * - Agent Testing Framework (mocks, simulation)
 */

import type { KernovaId, Timestamp, Priority } from './base.js';
import type { IntentType } from './intent.js';

// ─── Agent Planning ──────────────────────────────────────────

/**
 * A decomposed step within an execution plan.
 */
export interface PlanStep {
  id: KernovaId;
  index: number;
  description: string;
  dependencies: KernovaId[];       // Steps that must complete before this one
  status: PlanStepStatus;
  result?: unknown;
  error?: string;
  startedAt?: Timestamp;
  completedAt?: Timestamp;
  estimatedDurationMs?: number;
}

export type PlanStepStatus = 'pending' | 'ready' | 'executing' | 'completed' | 'failed' | 'skipped';

/**
 * A full execution plan generated by the planner.
 */
export interface ExecutionPlan {
  id: KernovaId;
  goal: string;
  steps: PlanStep[];
  status: PlanStatus;
  strategy: PlanStrategy;
  createdAt: Timestamp;
  updatedAt: Timestamp;
  completedAt?: Timestamp;
  totalSteps: number;
  completedSteps: number;
  failedSteps: number;
}

export type PlanStatus = 'planning' | 'executing' | 'completed' | 'failed' | 'cancelled';

export type PlanStrategy = 'sequential' | 'parallel' | 'adaptive';

export interface PlannerConfig {
  /** Maximum number of steps allowed in a plan */
  maxSteps?: number;              // default: 10
  /** Strategy for step execution ordering */
  strategy?: PlanStrategy;        // default: 'sequential'
  /** Whether to re-plan on step failure */
  adaptiveReplanning?: boolean;   // default: true
  /** Maximum re-plan attempts */
  maxReplanAttempts?: number;     // default: 2
  /** Model purpose key for the planning call */
  modelPurpose?: string;
}

// ─── Self-Reflection ─────────────────────────────────────────

/**
 * Result of a self-reflection evaluation.
 */
export interface ReflectionResult {
  id: KernovaId;
  intentId: KernovaId;
  originalOutput: string;
  evaluation: ReflectionEvaluation;
  revisedOutput?: string;
  reflectedAt: Timestamp;
  iterationCount: number;
}

export interface ReflectionEvaluation {
  /** Overall confidence score clamped to [0.0, 1.0] range. Represents the quality of an agent's response. */
  score: number;
  /** Whether the score meets or exceeds the configured threshold */
  passed: boolean;
  /** Per-criterion evaluation scores */
  criteria: ReflectionCriterion[];
  /** Human-readable reasoning for the overall score */
  reasoning: string;
  /** Suggested improvements if the score is below threshold */
  suggestions: string[];
}

export interface ReflectionCriterion {
  /** Criterion name (e.g., 'accuracy', 'completeness', 'clarity') */
  name: string;
  /** Confidence score for this criterion, clamped to [0.0, 1.0] range */
  score: number;
  /** Feedback explaining the score */
  feedback: string;
}

export interface ReflectionConfig {
  /** Minimum quality score to pass (0.0–1.0) */
  threshold?: number;             // default: 0.7
  /** Maximum reflection iterations */
  maxIterations?: number;         // default: 3
  /** Criteria to evaluate against */
  criteria?: string[];            // default: ['accuracy', 'completeness', 'clarity']
  /** Custom evaluation prompt */
  evaluationPrompt?: string;
  /** Model purpose key for reflection call */
  modelPurpose?: string;
}

// ─── Conversation History Manager ────────────────────────────

export interface ConversationMessage {
  id: KernovaId;
  role: 'user' | 'assistant' | 'system';
  content: string;
  timestamp: Timestamp;
  tokenEstimate: number;
  metadata?: Record<string, unknown>;
}

export interface ConversationSummary {
  id: KernovaId;
  content: string;
  messagesStart: number;          // index of first summarized message
  messagesEnd: number;            // index of last summarized message
  messageCount: number;
  createdAt: Timestamp;
  tokenEstimate: number;
}

export interface ConversationWindow {
  messages: ConversationMessage[];
  summaries: ConversationSummary[];
  totalMessages: number;
  windowStart: number;            // current window start index
  tokenCount: number;
}

export interface ConversationConfig {
  /** Maximum token budget for the conversation window */
  maxTokens?: number;             // default: 4000
  /** Number of recent messages to always keep */
  preserveRecent?: number;        // default: 10
  /** Whether to auto-summarize when window overflows */
  autoSummarize?: boolean;        // default: true
  /** Token threshold to trigger summarization */
  summarizeThreshold?: number;    // default: 0.8 (80% of maxTokens)
  /** Model purpose key for summarization call */
  modelPurpose?: string;
}

// ─── RAG Pipeline ────────────────────────────────────────────

export interface Document {
  id: KernovaId;
  content: string;
  source: string;                 // file path, URL, etc.
  metadata?: Record<string, unknown>;
  createdAt: Timestamp;
}

export interface DocumentChunk {
  id: KernovaId;
  documentId: KernovaId;
  content: string;
  index: number;                  // chunk position in document
  embedding?: number[];
  metadata?: Record<string, unknown>;
  tokenEstimate: number;
}

export interface RetrievalResult {
  chunk: DocumentChunk;
  score: number;                  // similarity score (0.0–1.0)
  document: Document;
}

export interface RAGConfig {
  /** Chunk size in tokens */
  chunkSize?: number;             // default: 512
  /** Overlap between chunks in tokens */
  chunkOverlap?: number;          // default: 50
  /** Maximum results to return from retrieval */
  topK?: number;                  // default: 5
  /** Minimum similarity score threshold */
  scoreThreshold?: number;        // default: 0.7
  /** Chunking strategy */
  chunkStrategy?: ChunkStrategy;  // default: 'recursive'
}

export type ChunkStrategy = 'fixed' | 'recursive' | 'sentence' | 'paragraph';

// ─── Agent Testing Framework ─────────────────────────────────

export interface TestScenario {
  id: KernovaId;
  name: string;
  description: string;
  messages: TestMessage[];
  expectedBehavior: ExpectedBehavior;
  timeout?: number;               // default: 30_000 ms
}

export interface TestMessage {
  role: 'user' | 'system';
  content: string;
  delay?: number;                 // ms to wait before sending
}

export interface ExpectedBehavior {
  /** Patterns the response should match */
  shouldContain?: string[];
  /** Patterns the response should NOT match */
  shouldNotContain?: string[];
  /** Tool calls that should be made */
  toolCalls?: ExpectedToolCall[];
  /** Maximum allowed response time */
  maxDurationMs?: number;
  /** Custom validator function name */
  validator?: string;
}

export interface ExpectedToolCall {
  toolName: string;
  args?: Record<string, unknown>;
  shouldSucceed?: boolean;
}

export interface TestResult {
  scenarioId: KernovaId;
  scenarioName: string;
  passed: boolean;
  duration: number;
  assertions: AssertionResult[];
  response?: string;
  toolCalls?: Array<{ tool: string; args: unknown; result: unknown }>;
  error?: string;
}

export interface AssertionResult {
  description: string;
  passed: boolean;
  expected?: unknown;
  actual?: unknown;
}

export interface MockProviderConfig {
  /** Canned responses indexed by prompt pattern */
  responses?: Record<string, string>;
  /** Default response if no pattern matches */
  defaultResponse?: string;
  /** Simulated latency in ms */
  latencyMs?: number;
  /** Whether to simulate failures */
  shouldFail?: boolean;
  /** Error message for simulated failures */
  failureMessage?: string;
}
